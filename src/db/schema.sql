CREATE TABLE IF NOT EXISTS ot_users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(48) NOT NULL UNIQUE,
 display_name VARCHAR(120) NOT NULL,
 password_hash VARCHAR(180) NOT NULL,
 role ENUM('admin','learner') NOT NULL DEFAULT 'learner',
 active TINYINT NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ot_labs (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(160) NOT NULL,
 summary VARCHAR(400) NOT NULL,
 lesson TEXT NOT NULL,
 mission TEXT NOT NULL,
 simulator VARCHAR(20) NOT NULL,
 image_id INT NOT NULL,
 target INT NOT NULL DEFAULT 0,
 sort_order INT NOT NULL DEFAULT 0,
 published TINYINT NOT NULL DEFAULT 1,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 archived TINYINT NOT NULL DEFAULT 0
) ENGINE=InnoDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ot_sessions (
 token CHAR(64) PRIMARY KEY,
 user_id INT UNSIGNED NOT NULL,
 csrf CHAR(64) NOT NULL,
 expires_at BIGINT NOT NULL,
 last_seen BIGINT NOT NULL,
 FOREIGN KEY (user_id) REFERENCES ot_users(id) ON DELETE CASCADE,
 INDEX (expires_at)
) ENGINE=InnoDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ot_runs (
 id CHAR(64) PRIMARY KEY,
 user_id INT UNSIGNED NOT NULL,
 lab_id INT UNSIGNED NOT NULL,
 revision INT UNSIGNED NOT NULL,
 simulator VARCHAR(20) NOT NULL,
 target INT NOT NULL,
 state LONGTEXT NOT NULL,
 version INT UNSIGNED NOT NULL DEFAULT 0,
 actions INT UNSIGNED NOT NULL DEFAULT 0,
 score INT NOT NULL DEFAULT 0,
 status ENUM('active','passed','abandoned') NOT NULL DEFAULT 'active',
 last_action_id CHAR(64),
 started_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 finished_at DATETIME,
 FOREIGN KEY (user_id) REFERENCES ot_users(id),
 FOREIGN KEY (lab_id) REFERENCES ot_labs(id),
 INDEX (user_id, lab_id, status)
) ENGINE=InnoDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ot_audit (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 actor VARCHAR(48) NOT NULL,
 action VARCHAR(80) NOT NULL,
 detail VARCHAR(1000) NOT NULL DEFAULT '',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX (created_at)
) ENGINE=InnoDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ot_settings (
 setting_key VARCHAR(40) PRIMARY KEY,
 setting_value TEXT NOT NULL
) ENGINE=InnoDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ot_migrations (
 version INT PRIMARY KEY,
 applied_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ot_login_limits (
 identity CHAR(64) PRIMARY KEY,
 failures INT NOT NULL DEFAULT 0,
 expires_at BIGINT NOT NULL,
 INDEX (expires_at)
) ENGINE=InnoDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
